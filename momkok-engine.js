  function bindTierButtonsAndSyncLabels() {
    document.querySelectorAll('a, button, span, div, h3, h4, p, td, th').forEach(el => {
      if (el.children.length === 0 && el.textContent && el.textContent.includes('15장')) {
        el.textContent = el.textContent.replace(/15장/g, '20장');
      }
    });

    const btnFree = document.getElementById('btnTierFree');
    const btnBasic = document.getElementById('btnTierBasic');
    const btnMaster = document.getElementById('btnTierMaster');

    if (btnFree) {
      btnFree.onclick = function (e) {
        e.preventDefault();
        window.activateMomkokTier('free', true);
      };
    }
    if (btnBasic) {
      btnBasic.onclick = function (e) {
        e.preventDefault();
        window.activateMomkokTier('basic', true);
      };
    }
    if (btnMaster) {
      btnMaster.onclick = function (e) {
        e.preventDefault();
        window.activateMomkokTier('master', true);
      };
    }

    // free.html, basic.html, master.html 상단 네비게이션 버튼 클릭 시에도 즉시 초기화 작동
    document.querySelectorAll('.top-tier-nav .tier-nav-item').forEach(a => {
      a.onclick = function (e) {
        const href = (a.getAttribute('href') || '').toLowerCase();
        if (href.includes('free.html')) {
          e.preventDefault();
          window.activateMomkokTier('free', true);
        } else if (href.includes('basic.html')) {
          e.preventDefault();
          window.activateMomkokTier('basic', true);
        } else if (href.includes('master.html')) {
          e.preventDefault();
          window.activateMomkokTier('master', true);
        }
      };
    });
  }

